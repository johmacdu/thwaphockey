// test/app-icon-dark-variants.test.js
//
// Consistency test for the light/dark app-icon variants. A build is needed to
// verify iOS actually swaps light<->dark, but we CAN guarantee the generated
// data stays coherent: every icon has a darker dark background, a dark preview,
// and a valid iOS 18 appearance set (light + dark images with the right
// luminosity metadata) staged for the asset catalog.

import { describe, it, expect } from 'vitest';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'app-icons/manifest.json'), 'utf8'));

const lum = (hex) => {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

describe('Light/dark app-icon variants', () => {
  it('every icon has a dark hex that is genuinely darker than its light hex', () => {
    expect(manifest.icons.length).toBe(20);
    for (const ic of manifest.icons) {
      expect(ic.darkHex, `${ic.skill}/${ic.color} darkHex`).toMatch(/^#[0-9A-F]{6}$/);
      expect(lum(ic.darkHex), `${ic.skill}/${ic.color} darker`).toBeLessThan(lum(ic.hex));
    }
  });

  it('every icon ships a dark preview next to its light preview', () => {
    for (const ic of manifest.icons) {
      expect(existsSync(resolve(root, ic.preview)), ic.preview).toBe(true);
      expect(existsSync(resolve(root, ic.darkPreview)), ic.darkPreview).toBe(true);
    }
  });

  it('every icon has a valid iOS 18 appearance set (light + dark with luminosity metadata)', () => {
    // The 1024 master PNGs are gitignored (regenerated by the generator); the
    // Contents.json structure is committed and is what we validate here.
    for (const ic of manifest.icons) {
      const dir = resolve(root, 'app-icons/ios-appearance', ic.appearanceSet);
      expect(ic.appearanceSet.endsWith('.appiconset')).toBe(true);
      const c = JSON.parse(readFileSync(resolve(dir, 'Contents.json'), 'utf8'));
      const light = c.images.find((x) => !x.appearances);
      const dark = c.images.find((x) => x.appearances);
      expect(light && light.filename).toBe('icon-light.png');
      expect(dark && dark.filename).toBe('icon-dark.png');
      expect(dark.appearances[0]).toMatchObject({ appearance: 'luminosity', value: 'dark' });
    }
  });

  it('appearance-set names match the iOS alternate-icon keys (so setAlternateIconName lines up)', () => {
    for (const ic of manifest.icons) {
      expect(ic.appearanceSet).toBe(`${ic.iosKey}.appiconset`);
    }
  });
});
