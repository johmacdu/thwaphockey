// scripts/drills-inline-block.mjs
//
// The generated <script> block that carries lib/drills.js into index.html.
// Shared by scripts/gen-drills-inline.mjs (writes it) and
// test/drills-inline-drift.test.js (checks it).

export const BEGIN = '/* THWAP-DRILLS:BEGIN */';
export const END = '/* THWAP-DRILLS:END */';

export async function inlineDrillsBlock() {
  const { createThwapDrills } = await import('../lib/drills.js');
  const src = createThwapDrills.toString();
  if (/<\/script|<!--/i.test(src)) throw new Error('lib/drills.js must not contain </script or <!-- (it is inlined into index.html)');
  return [
    BEGIN,
    '/* GENERATED by scripts/gen-drills-inline.mjs from lib/drills.js. Do not hand-edit:',
    '   change lib/drills.js, then run  node scripts/gen-drills-inline.mjs  */',
    'window.ThwapDrills=(' + src + ')(window);',
    END,
  ].join('\n');
}

// Replace the text between the markers (markers included). Throws when the
// markers are missing, so a bad edit cannot silently drop the library.
export function replaceDrillsBlock(html, block) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('THWAP-DRILLS markers not found in index.html');
  return html.slice(0, a) + block + html.slice(b + END.length);
}

export function currentDrillsBlock(html) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) return null;
  return html.slice(a, b + END.length);
}
