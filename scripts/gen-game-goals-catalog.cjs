// scripts/gen-game-goals-catalog.cjs
//
// Regenerate lib/game_goals_catalog.js from the goal cards in
// hockey_game_goals.html, so the server's goal ids and titles match the page.
// Run: node scripts/gen-game-goals-catalog.cjs
// test/game-goals-server.test.js fails if the two drift apart.

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'hockey_game_goals.html'), 'utf8');

function decode(s) {
  return String(s)
    .replace(/&amp;/g, '&').replace(/&rsquo;/g, '\u2019').replace(/&lsquo;/g, '\u2018')
    .replace(/&#x27;/g, "'").replace(/&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').trim();
}

// Walk the sections so each goal knows which position group it belongs to.
const goals = [];
const secRe = /<section class="section ([^"]+)">([\s\S]*?)<\/section>/g;
let sm;
while ((sm = secRe.exec(html))) {
  const cls = sm[1];
  const position = /pos-only-forward/.test(cls) ? 'F' : (/pos-only-defense/.test(cls) ? 'D' : 'all');
  const body = sm[2];
  const catM = /<span class="sh-txt"><h2>([\s\S]*?)<\/h2>/.exec(body);
  const category = catM ? decode(catM[1]) : '';
  const lblRe = /<label class="goal goal-(\d+)" for="g\1">([\s\S]*?)<\/label>/g;
  let lm;
  while ((lm = lblRe.exec(body))) {
    const inner = lm[2];
    const emoji = decode((/<div class="emoji">([\s\S]*?)<\/div>/.exec(inner) || [])[1] || '');
    const title = decode((/<h3>([\s\S]*?)<\/h3>/.exec(inner) || [])[1] || '');
    const cue = decode((/<div class="cue">([\s\S]*?)<\/div>/.exec(inner) || [])[1] || '');
    goals.push({ id: 'g' + lm[1], title, emoji, cue, category, position });
  }
}
goals.sort((a, b) => Number(a.id.slice(1)) - Number(b.id.slice(1)));

const out = `// lib/game_goals_catalog.js
//
// GENERATED by scripts/gen-game-goals-catalog.cjs from hockey_game_goals.html.
// Do not hand-edit: change the goal cards on the page, then re-run the script.
// The server uses this to validate saved picks and to give the watch the
// display text for each goal id. position: 'all' | 'F' (forward) | 'D' (defense).

export const GAME_GOALS = ${JSON.stringify(goals, null, 2)};

// How many goals make a full game plan. Must match TARGET in
// hockey_game_goals.html. When the coach has set a team goal it fills one slot,
// so the player picks one fewer.
export const GAME_GOAL_TARGET = 3;

const BY_ID = new Map(GAME_GOALS.map((g) => [g.id, g]));
export function gameGoalById(id) { return BY_ID.get(String(id || '')) || null; }
`;
fs.writeFileSync(path.join(root, 'lib', 'game_goals_catalog.js'), out);
console.log('wrote', goals.length, 'goals');
